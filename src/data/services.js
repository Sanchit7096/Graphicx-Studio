// Helper to look up a service by slug or any alias
export const getServiceBySlug = (slug) => {
  if (!slug) return null;
  const clean = slug.toLowerCase().trim();
  return services.find(
    (s) => s.slug === clean || (s.aliases && s.aliases.includes(clean))
  );
};

// Helper to get services by category
export const getServicesByCategory = (categoryId) => {
  const category = Object.values(serviceCategories).find(cat => cat.id === categoryId);
  if (!category) return [];
  return services.filter(service => category.services.includes(service.slug));
};

// Populate projectIds for each service based on serviceSlug or aliases
services.forEach(service => {
  service.projectIds = projects
    .filter(p => {
      if (p.serviceSlugs && Array.isArray(p.serviceSlugs)) {
        return p.serviceSlugs.includes(service.slug) || (service.aliases && service.aliases.some(a => p.serviceSlugs.includes(a)));
      }
      return p.serviceSlug === service.slug || (service.aliases && service.aliases.includes(p.serviceSlug));
    })
    .map(p => p.id);
});

